"""The well-known object lists a target set can stand for.

Each list is an ordered table of ``(name, simbad_id)`` pairs: the name
is the list's own designation and is what the candidate is called on
the sky view; the id is what the object is looked up as in SIMBAD.
The lists are fixed identifiers, so they are looked up by name rather
than searched: an identifier pattern search for "M %" would also match
Minkowski's "M 1-1" planetary nebulae.

SIMBAD does not know the Caldwell or Herschel 400 numbering at all, and
carries the Melotte and Collinder designations for only some of their
entries (Mel 6 is NGC 288, but SIMBAD has no "Mel 6" alias), so every
list is spelled out with the NGC/IC identifier each entry resolves
under, and only entries without one keep their own designation
("Collinder 399", the Coathanger; note SIMBAD takes "Collinder", not
"Cr"). Sources: the Caldwell, Melotte and Collinder tables on Wikipedia,
and the Astronomical League's Herschel 400 list in NGC order (Wikipedia's
table merges NGC 2371/2372 and lists M 76 as NGC 650 where the League
has NGC 651). Every id was checked to resolve in SIMBAD when the tables
were written; the network-marked test in tests/test_search.py repeats
that check.

Special cases: C 9 is the Cave Nebula (SH 2-155), C 14 the Double
Cluster (NGC 869; NGC 884 is the other half), C 41 the Hyades (Mel 25)
and C 99 the Coalsack, none of them NGC/IC objects. Collinder 42, 156,
227 and 246 are Melotte clusters, thirty Collinder numbers are best
known as Trumpler clusters, and Collinder 206 is the open cluster
NGC 2818 rather than the planetary nebula NGC 2818A inside it. A few
Collinder numbers name the same NGC/IC object twice (the catalogue does
too), so the resolver de-duplicates the ids it asks for.
"""

